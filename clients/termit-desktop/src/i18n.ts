export type MessageKey = keyof typeof messages.ru;

export function t(locale: Locale, key: MessageKey): string {
  return messages[locale][key] ?? messages.en[key] ?? key;
}

export function tabLabel(locale: Locale, tab: string): string {
  const key = `tab${tab.charAt(0).toUpperCase()}${tab.slice(1)}` as MessageKey;
  if (key in messages.ru) {
    return t(locale, key);
  }
  return tab.charAt(0).toUpperCase() + tab.slice(1);
}

export function stepLabel(locale: Locale, stepId: string): string {
  const key = `step_${stepId}` as MessageKey;
  if (key in messages.ru) {
    return t(locale, key);
  }
  return stepId;
}
